using namespace std;

const int MAX = 5100000;
const long long MOD = 998244353;

long long fac[MAX], finv[MAX], inv[MAX];

// テーブルを作る前処理
void COMinit() {
    fac[0] = fac[1] = 1;
    finv[0] = finv[1] = 1;
    inv[1] = 1;
    for (int i = 2; i < MAX; i++) {
        fac[i] = fac[i - 1] * i % MOD;
        inv[i] = MOD - inv[MOD % i] * (MOD / i) % MOD;
        finv[i] = finv[i - 1] * inv[i] % MOD;
    }
}

// 二項係数計算
long long COM(int n, int k) {
    if (n < k) return 0;
    if (n < 0 || k < 0) return 0;
    return fac[n] * (finv[k] * finv[n - k] % MOD) % MOD;
}

int main() {
    int A, B, C, D;
    cin >> A >> B >> C >> D;

    COMinit();

    long long ans = 0;
    for (int i = A + B + 1; i <= A + B + C + 1; i++) {
        ans += (COM(i - 1, B) * COM(A + B + C + D - i, D - 1)) % MOD;
        ans %= MOD;
    }
    cout << ans << endl;

    return 0;
}
